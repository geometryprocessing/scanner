def _new_card(parent: etree.Element, title: str) -> etree.Element:
    """
    Append a titled card div to *parent* and return the card body div.

    Usage
    -----
        card_body = _new_card(grid, "My Plot")
        img_bytes = my_function(...)
        _embed_image(card_body, img_bytes)
    """
    card = etree.SubElement(parent, "div", attrib={"class": "card"})
    h3 = etree.SubElement(card, "h3")
    h3.text = title
    body = etree.SubElement(card, "div", attrib={"class": "card-body"})
    return body


def _embed_image(
    parent: etree.Element,
    png_bytes: bytes,
    alt: str = "",
    mime: str = "image/png",
) -> etree.Element:
    """
    Embed *png_bytes* (or any image bytes) as a base64 <img> tag inside *parent*.

    Parameters
    ----------
    parent    : lxml element to append <img> to
    png_bytes : raw image bytes (PNG by default)
    alt       : alt-text
    mime      : MIME type, e.g. "image/png", "image/svg+xml"
    """
    b64 = base64.b64encode(png_bytes).decode()
    img = etree.SubElement(
        parent, "img",
        attrib={"src": f"data:{mime};base64,{b64}", "alt": alt, "class": "plot-img"},
    )
    return img


def _key_value_table(
    parent: etree.Element,
    data: dict[str, str],
) -> etree.Element:
    """Render a simple two-column key/value table."""
    tbl = etree.SubElement(parent, "table", attrib={"class": "kv-table"})
    for k, v in data.items():
        tr = etree.SubElement(tbl, "tr")
        th = etree.SubElement(tr, "th")
        th.text = k
        td = etree.SubElement(tr, "td")
        td.text = str(v)
    return tbl


