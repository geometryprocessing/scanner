def _append_summary_chips(parent: etree.Element, calibrations: dict) -> None:
    chips = {
        "Cameras": str(len(calibrations)),
    }
    all_errs = []
    for cal in calibrations.values():
        if cal.get("per_view_errors") is not None:
            all_errs.extend(np.asarray(cal["per_view_errors"]).flatten().tolist())
    if all_errs:
        chips["Overall mean RMS"] = f"{np.mean(all_errs):.4f} px"
        chips["Overall max RMS"]  = f"{np.max(all_errs):.4f} px"

    for k, v in chips.items():
        chip = etree.SubElement(parent, "div", attrib={"class": "chip"})
        label = etree.SubElement(chip, "span", attrib={"class": "chip-label"})
        label.text = k
        val = etree.SubElement(chip, "span", attrib={"class": "chip-value"})
        val.text = v


def _append_camera_chips(
    parent: etree.Element, cam_id: str, cal: dict
) -> None:
    chips: dict[str, str] = {}

    if cal.get("image_shape"):
        w, h = cal["image_shape"]
        chips["Resolution"] = f"{w} × {h}"

    K = cal.get("K")
    if K is not None:
        chips["fx"] = f"{K[0,0]:.1f} px"
        chips["fy"] = f"{K[1,1]:.1f} px"

    dist = cal.get("dist_coeeffs")
    if dist is not None:
        chips["Dist coeffs"] = str(np.asarray(dist).flatten().shape[0])

    errs = cal.get("per_view_errors")
    if errs is not None:
        e = np.asarray(errs).flatten()
        chips["Views"] = str(len(e))
        chips["Mean RMS"] = f"{e.mean():.4f} px"

    for k, v in chips.items():
        chip = etree.SubElement(parent, "div", attrib={"class": "chip"})
        label = etree.SubElement(chip, "span", attrib={"class": "chip-label"})
        label.text = k
        val = etree.SubElement(chip, "span", attrib={"class": "chip-value"})
        val.text = v


