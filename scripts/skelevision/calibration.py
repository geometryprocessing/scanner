def _svg_bar_chart(
    values: np.ndarray,
    xlabel: str = "",
    ylabel: str = "",
    width: int = 480,
    height: int = 200,
) -> bytes:
    n = len(values)
    if n == 0:
        raise ValueError("empty array")

    pad_l, pad_r, pad_t, pad_b = 48, 16, 16, 36
    inner_w = width - pad_l - pad_r
    inner_h = height - pad_t - pad_b

    vmax = float(values.max()) * 1.15 or 1.0
    bar_w = max(1, inner_w / n - 1)

    svg = etree.Element("svg", attrib={
        "xmlns": "http://www.w3.org/2000/svg",
        "viewBox": f"0 0 {width} {height}",
        "width": str(width), "height": str(height),
    })

    # Background
    etree.SubElement(svg, "rect", attrib={
        "width": str(width), "height": str(height),
        "fill": "#181c24",
    })

    # Y gridlines + labels
    for frac in [0, 0.25, 0.5, 0.75, 1.0]:
        y = pad_t + inner_h * (1 - frac)
        etree.SubElement(svg, "line", attrib={
            "x1": str(pad_l), "x2": str(pad_l + inner_w),
            "y1": str(y), "y2": str(y),
            "stroke": "#2e3340", "stroke-width": "1",
        })
        txt = etree.SubElement(svg, "text", attrib={
            "x": str(pad_l - 4), "y": str(y + 4),
            "text-anchor": "end", "font-size": "9",
            "fill": "#8892a4", "font-family": "monospace",
        })
        txt.text = f"{vmax * frac:.3f}"

    # Bars
    mean_val = float(values.mean())
    for i, v in enumerate(values):
        x = pad_l + i * (inner_w / n)
        bar_h = (v / vmax) * inner_h
        # color = "#ef4444" if v > mean_val * 2 else "#38bdf8"
        color = "#ef4444" if v > ERROR_THRESHOLD else "#38bdf8"
        etree.SubElement(svg, "rect", attrib={
            "x": str(x), "y": str(pad_t + inner_h - bar_h),
            "width": str(bar_w), "height": str(bar_h),
            "fill": color, "rx": "1",
        })

    # Mean line
    mean_y = pad_t + inner_h * (1 - mean_val / vmax)
    etree.SubElement(svg, "line", attrib={
        "x1": str(pad_l), "x2": str(pad_l + inner_w),
        "y1": str(mean_y), "y2": str(mean_y),
        "stroke": "#fbbf24", "stroke-width": "1",
        "stroke-dasharray": "4 3",
    })
    mean_lbl = etree.SubElement(svg, "text", attrib={
        "x": str(pad_l + inner_w - 2), "y": str(mean_y - 3),
        "text-anchor": "end", "font-size": "9",
        "fill": "#fbbf24", "font-family": "monospace",
    })
    mean_lbl.text = f"mean {mean_val:.4f}"

    # Axes
    etree.SubElement(svg, "line", attrib={
        "x1": str(pad_l), "x2": str(pad_l),
        "y1": str(pad_t), "y2": str(pad_t + inner_h),
        "stroke": "#4b5563", "stroke-width": "1.5",
    })
    etree.SubElement(svg, "line", attrib={
        "x1": str(pad_l), "x2": str(pad_l + inner_w),
        "y1": str(pad_t + inner_h), "y2": str(pad_t + inner_h),
        "stroke": "#4b5563", "stroke-width": "1.5",
    })

    # Axis labels
    if xlabel:
        xl = etree.SubElement(svg, "text", attrib={
            "x": str(pad_l + inner_w / 2),
            "y": str(height - 4),
            "text-anchor": "middle", "font-size": "10",
            "fill": "#8892a4", "font-family": "sans-serif",
        })
        xl.text = xlabel

    if ylabel:
        yl = etree.SubElement(svg, "text", attrib={
            "transform": f"rotate(-90) translate(-{pad_t + inner_h//2},12)",
            "text-anchor": "middle", "font-size": "10",
            "fill": "#8892a4", "font-family": "sans-serif",
        })
        yl.text = ylabel

    return etree.tostring(svg)


