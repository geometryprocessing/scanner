def handle_extension(ext: str):
    import string
    clean_ext = ext.lower()
    clean_ext.translate(str.maketrans('', '', string.punctuation))
    return clean_ext 

def load_images(path: str, extension: str = 'png'):
    """
    Parameters
    ----------
    path : path to folder containing calibration images (for a single camera!)
    extension : which extension to look for when loading images. Default 'png'
    
    Returns
    -------
    imgs : list of loaded images (as numpy arrays)
    paths : list of paths to the images

    """
    imgs = []
    paths = get_all_paths(path, extensions=[extension])
    for path in paths:
        img = load_ldr(path)
        # new_img = (np.sqrt(img/(2**16-1))*255).astype(np.uint8)
        # new_path = path.replace('.tiff', '.png').replace('images_', 'ldr_images_')
        # print(new_path)
        # os.makedirs(os.path.dirname(new_path), exist_ok=True)
        # save_ldr(new_path, new_img)
        imgs += [img]
    return imgs, paths


def detect_markers(imgs: list, charuco: Charuco):
    """
    Parameters
    ----------
    imgs : list of images (all are numpy arrays)
    charuco : Charuco class containing board information for marker detection 
    
    Returns
    -------
    image points : camera pixels of detected charuco corners
    object points : 3D positions corresponding to charuco corners on the board
    ids : ids corresponding to detected charuco markers
    valid_idx : indices of image list that have more than MINIMUM_NUM_MARKERS detected
    invalid_idx : indices of image list that have fewer than MINIMUM_NUM_MARKERS detected
    """
    valid_idx, invalid_idx = set(), set()
    img_points, obj_points, ids = [], [], []
    for idx, img in enumerate(imgs):
        _img_points, _obj_points, _ids = charuco.detect_markers(img)
        if len(_ids) > MINIMUM_NUM_MARKERS:
            valid_idx.add(idx)
        else:
            invalid_idx.add(idx)
        img_points += [_img_points.squeeze()]
        obj_points += [_obj_points.squeeze()]
        ids += [_ids.squeeze()]
    return img_points, obj_points, ids, valid_idx, invalid_idx

