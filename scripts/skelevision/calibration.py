def _build_head(title: str) -> etree.Element:
    head = etree.Element("head")
    meta_charset = etree.SubElement(head, "meta", attrib={"charset": "UTF-8"})
    meta_viewport = etree.SubElement(head, "meta", attrib={
        "name": "viewport", "content": "width=device-width, initial-scale=1"
    })
    t = etree.SubElement(head, "title")
    t.text = title
    style = etree.SubElement(head, "style")
    style.text = _CSS
    return head


def _missing(parent: etree.Element, key: str) -> None:
    p = etree.SubElement(parent, "p", attrib={"class": "missing"})
    p.text = f"[WARNING] '{key}' not found in calibration dict."


def _slug(cam_id: str) -> str:
    return cam_id.replace(" ", "-").replace("/", "-")


