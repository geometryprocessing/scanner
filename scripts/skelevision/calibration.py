def _card_intrinsic_matrix(parent: etree.Element, K: np.ndarray | None) -> None:
    card_body = _new_card(parent, "Intrinsic Matrix  K")
    if K is None:
        _missing(card_body, "K")
        return

    fx, fy = K[0, 0], K[1, 1]
    cx, cy = K[0, 2], K[1, 2]
    skew = K[0, 1]

    # Rendered matrix
    tbl = etree.SubElement(card_body, "table", attrib={"class": "matrix-table"})
    for row in K:
        tr = etree.SubElement(tbl, "tr")
        for val in row:
            td = etree.SubElement(tr, "td")
            td.text = f"{val:.4f}"

    # Named parameters below
    _key_value_table(card_body, {
        "fx (px)":  f"{fx:.4f}",
        "fy (px)":  f"{fy:.4f}",
        "cx (px)":  f"{cx:.4f}",
        "cy (px)":  f"{cy:.4f}",
        "skew":     f"{skew:.6f}",
        "aspect ratio fy/fx": f"{fy/fx:.6f}" if fx != 0 else "—",
    })


def _card_distortion(parent: etree.Element, dist: np.ndarray | None) -> None:
    card_body = _new_card(parent, "Distortion Coefficients")
    if dist is None:
        _missing(card_body, "dist")
        return

    d = np.asarray(dist).flatten()
    labels = ["k1", "k2", "p1", "p2", "k3", "k4", "k5", "k6",
              "s1", "s2", "s3", "s4", "τx", "τy"]
    _key_value_table(card_body, {
        labels[i] if i < len(labels) else f"d{i}": f"{v:.8f}"
        for i, v in enumerate(d)
    })


